"""Writes version_info.txt (Windows .exe file properties) from APP_VERSION.

Used by build.py (build.bat).
"""
import sys

from . import APP_AUTHOR, APP_AUTHOR_EMAIL, APP_NAME, APP_VERSION

TEMPLATE = """# Windows file properties for {name}.exe - GENERATED by `python -m localdevx.buildinfo`.
# Edit APP_VERSION in localdevx/__init__.py instead of this file.
VSVersionInfo(
  ffi=FixedFileInfo(filevers={nums}, prodvers={nums}, mask=0x3f, flags=0x0,
                    OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', '{author}'),
      StringStruct('FileDescription', '{name} - local development manager for XAMPP'),
      StringStruct('FileVersion', '{ver}'),
      StringStruct('InternalName', '{name}'),
      StringStruct('LegalCopyright', 'Copyright (c) 2026 {author} <{email}>'),
      StringStruct('OriginalFilename', '{name}.exe'),
      StringStruct('ProductName', '{name}'),
      StringStruct('ProductVersion', '{ver}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def write_icon(path):
    """App icon with large sizes for the .exe, installer and shortcuts (the tray uses the small ones)."""
    from .tray import build_ico
    with open(path, "wb") as f:
        f.write(build_ico(sizes=(16, 20, 24, 32, 40, 48, 64, 128, 256)))


def render():
    parts = [int(p) for p in APP_VERSION.split(".") if p.isdigit()][:4]
    nums = tuple(parts + [0] * (4 - len(parts)))
    return TEMPLATE.format(name=APP_NAME, ver=APP_VERSION, nums=nums, author=APP_AUTHOR, email=APP_AUTHOR_EMAIL)


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "version_info.txt"
    with open(out, "w", encoding="utf-8") as f:
        f.write(render())
    print(f"Wrote {out} for {APP_NAME} v{APP_VERSION}")
